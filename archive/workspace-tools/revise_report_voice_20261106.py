OUTDIR.mkdir(parents=True, exist_ok=True)
if DEST.exists():
    raise SystemExit('Output already exists')
with ZipFile(SOURCE) as z:
    entries = [(i,z.read(i.filename)) for i in z.infolist()]
data = {i.filename:b for i,b in entries}
doc = E.fromstring(data['word/document.xml'])
paragraphs = doc.xpath('//w:p',namespaces=NS)
assert len(paragraphs)==206
changes=[]
for i,new in REVISIONS.items():
    p=paragraphs[i]
    assert not p.xpath('.//w:drawing|.//w:pict|.//w:instrText',namespaces=NS), i
    ts=p.xpath('.//w:t',namespaces=NS)
    assert ts, i
    old=''.join(t.text or '' for t in ts)
    ts[0].text=new
    ts[0].set('{http://www.w3.org/XML/1998/namespace}space','preserve')
    for t in ts[1:]:
        t.getparent().remove(t)
    # Existing fonts, paragraph styles, indentation and all bookmarks are retained.
    changes.append({'paragraph':i,'before':old,'after':new})

data['word/document.xml']=E.tostring(doc,encoding='UTF-8',xml_declaration=True,standalone=True)
with ZipFile(DEST,'w') as z:
    for entry,original in entries:
        z.writestr(entry,data[entry.filename])
with ZipFile(DEST) as z:
    assert all(z.read(i.filename)==b for i,b in entries if i.filename.startswith('word/media/'))
record={'source':str(SOURCE),'source_sha256':sha256(SOURCE.read_bytes()).hexdigest(),
        'output':str(DEST),'paragraphs_revised':len(changes),'images_preserved':15,'changes':changes}
(OUTDIR/'文字修改对照.json').write_text(json.dumps(record,ensure_ascii=False,indent=2),encoding='utf-8')
(OUTDIR/'修订后正文.txt').write_text('\n\n'.join(''.join(p.xpath('.//w:t/text()',namespaces=NS)) for p in paragraphs[67:]),encoding='utf-8')
print(json.dumps({k:v for k,v in record.items() if k!='changes'},ensure_ascii=False))
